// Bundles game word lists into words.generated.ts next to each game.
// Workers cannot read the filesystem at runtime, so the lists are compiled into the code.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// Games with a word list, and the longest word or phrase each one accepts.
const GAMES = { codenames: 30 };

function readWordList(file) {
  const words = [];
  const seen = new Set();
  for (const line of readFileSync(file, "utf8").replace(/^\uFEFF/, "").split(/\r?\n/)) {
    const word = line.trim().replace(/\s+/g, " ");
    const key = word.toLocaleLowerCase("en-US");
    if (!word || seen.has(key)) continue;
    seen.add(key);
    words.push(word);
  }
  return words;
}

function capitalizeWord(word) {
  if (word.toLocaleLowerCase("en-US") === "31seconds") return "31 Seconds";
  return word.split("-").map(part => {
    const match = part.match(/^([^\p{L}\p{N}]*)([\p{L}\p{M}]+)(.*)$/u);
    if (!match) return part;
    const [, prefix, letters, suffix] = match;
    const lower = letters.toLocaleLowerCase("en-US");
    const capitalized = lower === "bmw"
      ? "BMW"
      : letters === lower
        ? letters[0].toLocaleUpperCase("en-US") + letters.slice(1)
        : letters;
    return `${prefix}${capitalized}${suffix}`;
  }).join("-");
}

function capitalizeEntry(entry) {
  return entry.split(/(\s+)/).map(part => /^\s+$/.test(part) ? part : capitalizeWord(part)).join("");
}

for (const [game, maxLength] of Object.entries(GAMES)) {
  const gameDir = join(root, "src", "games", game);
  const wordsDir = join(gameDir, "words");
  if (!existsSync(wordsDir)) throw new Error(`Missing ${wordsDir}`);

  const seen = new Set();
  const categories = {};
  const words = [];
  for (const file of readdirSync(wordsDir).filter(name => name.toLowerCase().endsWith(".txt")).sort()) {
    const categoryWords = [];
    for (const line of readFileSync(join(wordsDir, file), "utf8").split(/\r?\n/)) {
      const word = line.trim().replace(/\s+/g, " ");
      const key = word.toLowerCase();
      if (!word || word.length > maxLength || seen.has(key)) continue;
      seen.add(key);
      words.push(word);
      categoryWords.push(word);
    }
    categories[file.replace(/\.txt$/i, "")] = categoryWords;
  }

  const output = `// Generated by scripts/build-words.mjs from the words/ folder. Do not edit by hand.\nexport const WORD_CATEGORIES: Record<string, string[]> = ${JSON.stringify(categories, null, 0)};\nexport const WORDS: string[] = ${JSON.stringify(words, null, 0)};\n`;
  writeFileSync(join(gameDir, "words.generated.ts"), output);
  console.log(`${game}: bundled ${words.length} unique words from ${wordsDir}`);
}

const thirtyOneDir = join(root, "src", "games", "thirtyone");
const contentDir = join(root, "content", "31seconds");
const easyWords = readWordList(join(contentDir, "easy-words.txt"));
const seenThirtyOne = new Set(easyWords.map(word => word.toLocaleLowerCase("en-US")));
const hardWords = readWordList(join(contentDir, "hard-words.txt"))
  .filter(word => {
    const key = word.toLocaleLowerCase("en-US");
    if (seenThirtyOne.has(key)) return false;
    seenThirtyOne.add(key);
    return true;
  });
const formattedEasyWords = easyWords.map(capitalizeEntry);
const formattedHardWords = hardWords.map(capitalizeEntry);
if (!formattedEasyWords.length || !formattedHardWords.length) throw new Error("31 Seconds needs non-empty easy and hard word lists.");
const thirtyOneOutput = `// Generated by scripts/build-words.mjs from content/31seconds/. Do not edit by hand.\nexport const EASY_WORDS: string[] = ${JSON.stringify(formattedEasyWords)};\nexport const HARD_WORDS: string[] = ${JSON.stringify(formattedHardWords)};\n`;
writeFileSync(join(thirtyOneDir, "words.generated.ts"), thirtyOneOutput);
console.log(`thirtyone: bundled ${formattedEasyWords.length} easy and ${formattedHardWords.length} hard unique words from ${contentDir}`);
