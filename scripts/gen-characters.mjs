// Generates the character list used by the Kin draft from the rulebook markdown, for both the server and the client.
// Run after editing the characters: node scripts/gen-characters.mjs   (reads the markdown in voedgoem/src/games/kin/rulebook)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "..", "..", "voedgoem", "src", "games", "kin", "rulebook");
const outputs = [
  join(here, "..", "src", "games", "kin", "characters.data.ts"),
  join(here, "..", "..", "voedgoem", "src", "games", "kin", "characters.data.ts")
];

// Rulebook file -> Kin id (see kins.ts). 10-1-neutral-characters.md holds the neutral characters.
const FILES = {
  "10-1-neutral-characters.md": null,
  "12-1-kin-the-ethereal.md": "ethereal",
  "12-2-kin-dynasty-of-hanshu.md": "hanshu",
  "12-3-kin-wanderers.md": "wanderers",
  "12-4-kin-pride-of-lumon.md": "lumon",
  "12-5-kin-beastmen-tribes.md": "beastmen",
  "12-6-kin-archive-ark.md": "ark",
  "12-7-kin-hammers-of-the-ash.md": "hammers",
  "12-8-kin-seven-streams-syndicate.md": "syndicate",
  "12-9-kin-children-of-the-great-tree.md": "tree",
  "12-10-kin-deep-ones.md": "deepones"
};

const slug = name => name.toLowerCase().normalize("NFKD").replace(/[\u0300-\u036f]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const plain = text => text.replace(/\[\[([^\]|]+)(?:\|([^\]]+))?\]\]/g, (_, target, label) => label ?? target).replace(/\*\*/g, "").trim();

const characters = [];
for (const [file, kin] of Object.entries(FILES)) {
  const lines = readFileSync(join(source, file), "utf8").replace(/\r/g, "").split("\n");
  let current = null;
  let ability = null;
  let inShort = false;
  for (const line of lines) {
    const head = /^## ([^|]+)\|([^|]+)\|([^|]+)\|\s*(\d+) power\s*$/.exec(line);
    if (head) {
      const [, name, title, archetype, power] = head;
      const archetypes = archetype.toLowerCase().split(/\s+and\s+/).map(a => a.trim());
      current = { id: slug(name), name: name.trim(), title: title.trim(), archetypes, power: Number(power), kin, abilities: [] };
      characters.push(current);
      ability = null;
      continue;
    }
    if (/^#{1,2} /.test(line)) { current = null; continue; }
    if (!current || !line.startsWith(">")) continue;
    const text = line.slice(1).trim();
    const abilityHead = /^([^\x00-\x7f])\s+(.+)$/u.exec(text);
    if (abilityHead && !/^[\u201c\u201d]/.test(abilityHead[1])) {
      ability = { kind: abilityHead[1] === "\u21b7" ? "tap" : "passive", icon: abilityHead[1], name: plain(abilityHead[2]), text: "" };
      current.abilities.push(ability);
    } else if (/^No ability|^Has no ability/i.test(text)) {
      ability = null;
    } else if (ability && /^Short description:/i.test(text)) {
      ability.text = text.replace(/^Short description:\s*/i, "").trim();
      inShort = true;
    } else if (ability && inShort && text.startsWith("- ")) {
      ability.text += `\n${text.replace(/,\s*$/, "")}`;
    } else if (ability) {
      inShort = false;
      const detail = /^([A-Za-z][A-Za-z ]*):\s*(.+)$/.exec(text);
      if (detail) (current.notes ??= []).push(`${detail[1].trim()}: ${detail[2].trim()}`);
    }
  }
}

const header = "// Generated by voedgoem-server/scripts/gen-characters.mjs from the rulebook. Do not edit by hand.\n";
const body = `${header}export interface CharacterAbility {
  kind: "tap" | "passive";
  icon: string;
  name: string;
  text: string;
}

export type Archetype = "discovery" | "expansion" | "control" | "universal";

export interface CharacterDef {
  id: string;
  name: string;
  title: string;
  // "Discovery and Control" gives two archetypes; "universal" counts as all of them.
  archetypes: Archetype[];
  power: number;
  // Kin id, or null for a neutral character.
  kin: string | null;
  abilities: CharacterAbility[];
  // Trigger, effect and extra rules of the abilities, shown behind the info icon.
  notes?: string[];
}

export const CHARACTERS: readonly CharacterDef[] = ${JSON.stringify(characters, null, 2)};
`;
for (const out of outputs) writeFileSync(out, body);
const dupes = characters.map(c => c.id).filter((id, i, all) => all.indexOf(id) !== i);
console.log(`${characters.length} characters written.${dupes.length ? " DUPLICATE IDS: " + dupes.join(", ") : ""}`);
