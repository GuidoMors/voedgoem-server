import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const gamesDir = join(root, "src", "games");
const modules = [];

for (const directory of readdirSync(gamesDir, { withFileTypes: true })
  .filter(entry => entry.isDirectory())
  .map(entry => entry.name)
  .sort()) {
  const entryFile = join(gamesDir, directory, "index.ts");
  if (!existsSync(entryFile)) continue;

  const source = readFileSync(entryFile, "utf8");
  const exports = [...source.matchAll(/\bexport\s+const\s+([A-Za-z_$][\w$]*)\s*:\s*GameModule(?:\s*<[^>]+>)?\s*=/g)];
  if (exports.length !== 1) {
    throw new Error(`${entryFile} must export exactly one const typed as GameModule; found ${exports.length}.`);
  }

  modules.push({
    directory,
    exportName: exports[0][1],
    localName: `game_${directory.replace(/[^A-Za-z0-9_$]/g, "_")}`
  });
}

if (modules.length === 0) throw new Error(`No game modules found under ${gamesDir}.`);

const imports = modules.map(({ directory, exportName, localName }) =>
  `import { ${exportName} as ${localName} } from "./${directory}";`
).join("\n");
const entries = modules.map(({ localName }) =>
  `  [${localName}.info.id]: ${localName},`
).join("\n");
const output = `// Generated by scripts/build-game-registry.mjs. Do not edit by hand.
import type { GameModule } from "./types";
${imports}

export const MODULES: Record<string, GameModule<any>> = {
${entries}
};
`;

writeFileSync(join(gamesDir, "modules.generated.ts"), output);
console.log(`Generated registry for ${modules.length} games.`);
