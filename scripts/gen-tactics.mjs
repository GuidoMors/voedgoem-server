// Generates the names and texts of the tactics and subterfuge cards (24-tactics-subterfuge.md) for the server.
// Their behaviour is written in src/games/kin/tactics.ts and is keyed by card id, which is the slug of the heading.
// Run after editing a card: node scripts/gen-tactics.mjs   (kin.tactics.test.ts fails when an id has no behaviour)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "..", "..", "voedgoem", "src", "games", "kin", "rulebook", "24-tactics-subterfuge.md");
const output = join(here, "..", "src", "games", "kin", "tactics.data.ts");

const slug = name => name.toLowerCase().normalize("NFKD").replace(/[\u0300-\u036f]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const plain = text => text.replace(/\[\[([^\]|]+)(?:\|([^\]]+))?\]\]/g, (_, a, b) => b ?? a).replace(/\*\*/g, "");

const TAGS = { "🕀": "tactics", "☽": "subterfuge" };
const lists = { tactics: [], subterfuge: [] };
let current = null;

for (const raw of readFileSync(source, "utf8").replace(/\r/g, "").split("\n")) {
  const head = /^## (.*)$/.exec(raw);
  if (head) {
    const [name, tag] = head[1].split("|").map(s => s.trim());
    current = TAGS[tag] ? { list: lists[TAGS[tag]], name, short: [], then: [], target: null } : null;
    if (current) current.list.push(current);
    continue;
  }
  if (!current || !raw.startsWith(">")) continue;
  const line = raw.replace(/^>\s?/, "").trim();
  const label = /^([A-Za-z][A-Za-z' ]{0,30}):\s*(.*)$/.exec(line);
  if (label) {
    const key = label[1].toLowerCase();
    current.target = key === "short description" ? current.short : key === "then" ? current.then : null;
    if (current.target) current.target.push(label[2]);
  } else if (current.target && line) current.target.push(line);
}

const card = ({ name, short, then }) => ({
  id: slug(name),
  name,
  text: plain([...short, ...(then.length ? [`Then: ${then.join(" ")}`] : [])].join(" "))
});

const body = ["tactics", "subterfuge"].map(key => {
  const cards = lists[key].map(card);
  if (cards.some(c => !c.text)) throw new Error(`A ${key} card has no short description`);
  return `export const ${key.toUpperCase()}_CARDS: readonly { id: string; name: string; text: string }[] = ${JSON.stringify(cards, null, 2)};\n`;
});

writeFileSync(output, `// Generated by scripts/gen-tactics.mjs from the rulebook. Do not edit.\n${body.join("\n")}`);
console.log(`tactics.data.ts written (${lists.tactics.length} tactics, ${lists.subterfuge.length} subterfuge).`);
