// Generates the building list used by the Kin game from the rulebook, for both the server and the client.
// Run after editing a building header: node scripts/gen-buildings.mjs   (reads the markdown in voedgoem/src/games/kin/rulebook)
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "..", "..", "voedgoem", "src", "games", "kin", "rulebook");
const outputs = [
  join(here, "..", "src", "games", "kin", "buildings.data.ts"),
  join(here, "..", "..", "voedgoem", "src", "games", "kin", "buildings.data.ts")
];

// Rulebook file -> Kin id (see kins.ts); null for the shared blueprints.
const FILES = {
  "06-buildings.md": null,
  "12-1-kin-the-ethereal.md": "ethereal",
  "12-2-kin-dynasty-of-hanshu.md": "hanshu",
  "12-3-kin-wanderers.md": "wanderers",
  "12-4-kin-pride-of-lumon.md": "lumon",
  "12-5-kin-beastmen-tribes.md": "beastmen",
  "12-6-kin-archive-ark.md": "ark",
  "12-7-kin-hammers-of-the-ash.md": "hammers",
  "12-8-kin-seven-streams-syndicate.md": "syndicate",
  "12-9-kin-children-of-the-great-tree.md": "tree",
  "12-10-kin-deep-ones.md": "deepones"
};
const KINDS = { "\u2b22": "tile", "\u25fc": "center", "\u2a3a": "slice", "+": "cross", "/": "edge" };
const slug = name => name.toLowerCase().normalize("NFKD").replace(/[\u0300-\u036f]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const buildings = [];
for (const [file, kin] of Object.entries(FILES)) {
  const lines = readFileSync(join(source, file), "utf8").replace(/\r/g, "").split("\n");
  let current = null;
  for (const line of lines) {
    const head = /^## ([^|]+)\|\s*building blueprint\s*\|\s*(\S+)\s*(?:\|\s*(.*))?$/.exec(line);
    if (head) {
      const kind = KINDS[head[2]];
      if (!kind) throw new Error(`Unknown building type "${head[2]}" for ${head[1]}`);
      const icons = (head[3] ?? "").split(",").map(s => s.trim()).filter(Boolean);
      current = { id: slug(head[1]), name: head[1].trim(), kind, icons, kin, garrison: 0 };
      buildings.push(current);
      continue;
    }
    if (/^#{1,2} /.test(line)) { current = null; continue; }
    const garrison = current && /^> Garrison:\s*(\d+)/.exec(line);
    if (garrison) current.garrison = Number(garrison[1]);
  }
}

const body = `// Generated by voedgoem-server/scripts/gen-buildings.mjs from the rulebook. Do not edit by hand.
export type BuildingKind = "tile" | "center" | "slice" | "cross" | "edge";

export interface BuildingDef {
  id: string;
  name: string;
  kind: BuildingKind;
  // Cross and edge buildings have none. The Worksite has one per resource: farm, quarry, lumberyard.
  icons: string[];
  // Kin id for a faction building, or null for a shared blueprint.
  kin: string | null;
  garrison: number;
}

export const BUILDINGS: readonly BuildingDef[] = ${JSON.stringify(buildings, null, 2)};

export const buildingById = (id: string) => BUILDINGS.find(b => b.id === id);
`;
for (const out of outputs) writeFileSync(out, body);
const dupes = buildings.map(b => b.id).filter((id, i, all) => all.indexOf(id) !== i);
console.log(`${buildings.length} buildings written.${dupes.length ? " DUPLICATE IDS: " + dupes.join(", ") : ""}`);
void readdirSync;
